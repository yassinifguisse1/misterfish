import fs from "fs";
import path from "path";
import { fileURLToPath } from "url";

const __dirname = path.dirname(fileURLToPath(import.meta.url));
const root = path.join(__dirname, "..");
const sourceDir = path.join(root, "images");
const targetDir = path.join(root, "public/images/menu");
const menuTsPath = path.join(root, "src/data/menu.ts");
const mapPath = path.join(root, "src/data/dish-image-map.ts");

const normalize = (value) =>
  value
    .normalize("NFD")
    .replace(/\p{M}/gu, "")
    .toLowerCase()
    .replace(/[''`]/g, "'")
    .replace(/\s+/g, " ")
    .trim();

const aliases = {
  "paella valenciana": "payella valencianna",
};

function findImageFile(name, fileMap) {
  const candidates = [name, aliases[normalize(name)]].filter(Boolean);

  for (const candidate of candidates) {
    const exact = fileMap.get(normalize(candidate));
    if (exact) return exact;
  }

  const key = normalize(name);
  for (const [normalizedName, file] of fileMap) {
    if (normalizedName.replace(/[^a-z0-9]/g, "") === key.replace(/[^a-z0-9]/g, "")) {
      return file;
    }
  }

  return null;
}

const menuTs = fs.readFileSync(menuTsPath, "utf8");
const menuNames = [
  ...menuTs.matchAll(/\{ id: "[^"]+", name: "([^"]+)"/g),
].map((match) => match[1]);

const imageFiles = fs
  .readdirSync(sourceDir)
  .filter((file) => file.toLowerCase().endsWith(".webp"));

const fileMap = new Map(
  imageFiles.map((file) => [normalize(file.replace(/\.webp$/i, "")), file]),
);

fs.mkdirSync(targetDir, { recursive: true });

const dishImages = {};
const copied = [];

for (const file of imageFiles) {
  const target = path.join(targetDir, file);
  fs.copyFileSync(path.join(sourceDir, file), target);
  copied.push(file);
}

for (const name of menuNames) {
  const file = findImageFile(name, fileMap);
  if (file) dishImages[name] = file;
}

const mapContents = `// Auto-generated by scripts/sync-menu-images.mjs — do not edit manually
export const dishImages: Record<string, string> = ${JSON.stringify(dishImages, null, 2)};

export const DISH_IMAGE_BASE_PATH = "/images/menu";
`;

fs.writeFileSync(mapPath, mapContents);

console.log(`Copied ${copied.length} images to public/images/menu/`);
console.log(`Mapped ${Object.keys(dishImages).length} menu items to images`);
